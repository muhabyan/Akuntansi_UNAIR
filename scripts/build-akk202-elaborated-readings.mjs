// Rebuild reviewed AKM II elaborations without modifying the historical audit packs.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';

const selected = process.argv.slice(2).filter(arg => /^\d+$/.test(arg)).map(Number);
for (const tm of selected.length ? selected : [9, 10, 11, 12, 13, 14, 15]) {
  assert.ok(Number.isInteger(tm) && tm >= 9 && tm <= 15, 'Expected TM9–TM15');
  const folder = `TM${String(tm).padStart(2, '0')}/elaboration-20261014`;
  const source = new URL(`../content-pipeline/AKK202/${folder}/reading.json`, import.meta.url);
  const reading = JSON.parse(readFileSync(source, 'utf8'));
  assert.equal(reading.tm, tm);
  const target = new URL(`../src/data/akm2/modules/tm${tm}.ts`, import.meta.url);
  const output = `// Generated by scripts/build-akk202-elaborated-readings.mjs; edit content-pipeline/AKK202/${folder}/reading.json.
import type { Reading } from '../../../types';

export const TM${tm}_READING: Reading = ${JSON.stringify(reading, null, 2)};
`;
  if (process.argv.includes('--check')) assert.equal(readFileSync(target, 'utf8').replace(/\r\n/g, '\n'), output, `TM${tm} source/runtime mismatch`);
  else writeFileSync(target, output);
  console.log(`AKK202 TM${tm}: ${process.argv.includes('--check') ? 'source/runtime match' : 'rebuilt'}`);
}
