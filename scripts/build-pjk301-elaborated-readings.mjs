import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
for (const tm of [9, 10, 11, 12, 13, 14, 15]) {
  const folder = `TM${String(tm).padStart(2, '0')}/elaboration-20261014`;
  const r = JSON.parse(readFileSync(new URL(`../content-pipeline/PJK301/${folder}/reading.json`, import.meta.url), 'utf8'));
  assert.equal(r.tm, tm);
  const target = new URL(`../src/data/pjk2/modules/tm${tm}.ts`, import.meta.url);
  const output = `// Generated by scripts/build-pjk301-elaborated-readings.mjs; edit content-pipeline/PJK301/${folder}/reading.json.
import type { Reading } from '../../../types';
export const TM${tm}_READING: Reading = ${JSON.stringify(r, null, 2)};
`;
  if (process.argv.includes('--check')) assert.equal(readFileSync(target, 'utf8').replace(/\r\n/g, '\n'), output);
  else writeFileSync(target, output);
  console.log(`PJK301 TM${tm}: ${process.argv.includes('--check') ? 'source/runtime match' : 'rebuilt'}`);
}
