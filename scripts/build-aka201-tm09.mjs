// TM09 authoring source lives in the repository, including the unchanged figure data.
// Run with --check to verify that the served reading matches the reviewed source.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';

const source = new URL('../content-pipeline/AKA201/TM09/reading.json', import.meta.url);
const target = new URL('../src/data/pbri/modules/tm9.ts', import.meta.url);
const reading = JSON.parse(readFileSync(source, 'utf8'));
assert.equal(reading.tm, 9);
assert.equal(reading.layout, 'layered');
const output = `// Generated by scripts/build-aka201-tm09.mjs; edit content-pipeline/AKA201/TM09/reading.json.
// Source coverage and editorial decisions: content-pipeline/AKA201/TM09/coverage.md.
import type { Reading } from '../../../types';

export const TM9_READING: Reading = ${JSON.stringify(reading, null, 2)};
`;
if (process.argv.includes('--check')) {
  assert.equal(readFileSync(target, 'utf8').replace(/\r\n/g, '\n'), output, 'TM09 runtime differs from its authoring source');
  console.log('AKA201 TM09: authoring source and runtime match');
} else {
  writeFileSync(target, output);
  console.log('AKA201 TM09: reading rebuilt');
}
