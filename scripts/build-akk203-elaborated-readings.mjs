// Supersede historical post-UTS readings on the active course route.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
const tms = [8, 9, 10, 11, 13, 14];
const readings = Object.fromEntries(tms.map(tm => {
  const folder = `TM${String(tm).padStart(2, '0')}/elaboration-20261014`;
  const r = JSON.parse(readFileSync(new URL(`../content-pipeline/AKK203/${folder}/reading.json`, import.meta.url), 'utf8'));
  assert.equal(r.tm, tm);
  return [tm, r];
}));
const target = new URL('../src/data/asp/elaboratedReadings.ts', import.meta.url);
const output = `// Generated by scripts/build-akk203-elaborated-readings.mjs; edit content-pipeline/AKK203/TMxx/elaboration-20261014/reading.json.
import type { Reading } from '../../types';
export const ASP_ELABORATED_READINGS: Record<number, Reading> = ${JSON.stringify(readings, null, 2)};
`;
if (process.argv.includes('--check')) assert.equal(readFileSync(target, 'utf8').replace(/\r\n/g, '\n'), output);
else writeFileSync(target, output);
console.log(`ASP six active readings: ${process.argv.includes('--check') ? 'source/runtime match' : 'rebuilt'}`);
