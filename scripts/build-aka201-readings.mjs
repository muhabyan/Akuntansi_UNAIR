// Rebuild the reviewed post-UTS authoring sources; TM09 retains its dedicated builder.
import assert from 'node:assert/strict';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const selected = process.argv.slice(2).filter((arg) => /^\d+$/.test(arg)).map(Number);
for (const tm of selected.length ? selected : [10, 11, 12, 13, 14, 15]) {
  assert.ok(Number.isInteger(tm) && tm >= 10 && tm <= 15, 'Expected TM10–TM15');
  const folder = `TM${tm}`;
  const source = new URL(`../content-pipeline/AKA201/${folder}/reading.json`, import.meta.url);
  if (!existsSync(source) && selected.length === 0) continue;
  const reading = JSON.parse(readFileSync(source, 'utf8'));
  assert.equal(reading.tm, tm);
  assert.equal(reading.layout, 'layered');
  const target = new URL(`../src/data/pbri/modules/tm${tm}.ts`, import.meta.url);
  const output = `// Generated by scripts/build-aka201-readings.mjs; edit content-pipeline/AKA201/${folder}/reading.json.
// Editorial coverage: docs/pra-uas-elaboration-progress.md and content-pipeline/AKA201/${folder}/coverage.md.
import type { Reading } from '../../../types';

export const TM${tm}_READING: Reading = ${JSON.stringify(reading, null, 2)};
`;
  if (process.argv.includes('--check')) assert.equal(readFileSync(target, 'utf8').replace(/\r\n/g, '\n'), output, `${folder} source/runtime mismatch`);
  else writeFileSync(target, output);
  console.log(`AKA201 ${folder}: ${process.argv.includes('--check') ? 'source/runtime match' : 'rebuilt'}`);
}
